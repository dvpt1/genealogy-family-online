規定了網站管理方在
用戶為向網站管理方提出各種請求時（例如，
在網站上註冊、下單、

訂閱通知等）而提供的個人資料方面，對用戶有意保密的義務。

用戶提供個人資料時，

使用者透過填寫網站上的特定表格提供個人數據，

通常包括以下資訊：

</p>

<p>
3.2.1.

使用者的姓氏、名字、父名；</p>

<p>
3.2.2.

用戶的聯絡電話；</p>

<p>
3.2.3.

電子郵件地址；</p>

<p>
3.2.4.

使用者的居住地及其他
數據。 </p>

<p>
3.3.

網站管理方也致力於

保護個人數據，這些數據會在

造訪網站頁面的過程中自動傳輸：</p>

<p>
IP
地址；<br>

來自 Cookie 的資訊；<br>

關於瀏覽器（或其他造訪網站的程式）的資訊；<br>

訪問時間；<br>

訪問的
頁面地址；<br>

引薦來源網址（先前造訪的
頁面地址）等。 </p>

<p>
3.3.1.

停用 Cookie 可能會導致您無法

造訪本網站。 </p>

<p>
3.3.2.

本網站會收集有關您訪客的

IP 位址的統計資訊。此

資訊用於識別和解決技術問題，以及

控制已執行操作的正確性。 </p>

<p>
3.4.

除上述未提及的任何其他個人信息
（例如購買歷史記錄、

