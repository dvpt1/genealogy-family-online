<h2>1. 術語定義</h2>

<p>
1.1

本隱私權政策

使用以下術語：</p>

<p>
1.1.1.

「網站管理」－經授權的網站管理人員，

代表其行事，
組織和（或）執行個人資料處理，
並確定
個人資料處理的目的、

待處理的個人資料的組成、

以及對個人資料執行的操作。 </p>

<p>
1.1.2.

「個人資料」—任何與

直接或間接相關的、

明確或可確定的
個人（個人資料主體）相關的資訊。 </p>

<p>
1.1.3.

「個人資料處理」－指使用自動化工具或不使用自動化工具對個人資料進行的任何

操作或一系列

操作，包括收集、

記錄、系統化、累積、

儲存、

澄清（更新、

更改）、

提取、使用、

傳輸（分發、提供、

訪問）、

去個性化、

阻止、

刪除、

銷毀個人資料。 </p>

<p>
1.1.4.

「個人資料保密性」—強制規定
網站管理方不要求
允許在未經個人資料主體同意或存在其他合法
理由的情況下故意分發個人資料。 </p>

<p>
1.1.5.

“網站使用者（以下簡稱“使用者”）”

指透過網際網路存取本網站並為自身目的使用本網站的人員。 </p>

<p>
1.1.6.

「Cookie」是一小段數據，
由網路伺服器傳送並儲存於
在使用者的電腦上，
每次使用者透過網頁用戶端或網頁​​瀏覽器向網頁伺服器傳送HTTP請求時，
都會儲存這些數據，

當使用者嘗試開啟對應的網頁時，

網站也會發送這些數據。 </p>

<p>1.1.7.

「IP位址」是電腦網路中一個唯一的網路位址，

該網路是透過IP協定建構的。 </p>

